#!/usr/bin/python3
"""Bake the optional TTF argument offline using Pillow, numpy and scipy."""

import argparse
from dataclasses import dataclass
import hashlib
from pathlib import Path

import numpy as np
import PIL
from PIL import Image, ImageDraw, ImageFont, features
import scipy
from scipy.ndimage import distance_transform_edt


FONT_SIZE = 48
ATLAS_WIDTH = 2048
SDF_RANGE = 32.0
PADDING = 34
CODEPOINTS = tuple(range(32, 127)) + tuple(range(160, 256))
SPACES = (32, 160)
DEFAULT_TTF = Path('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf')
OUTPUT_DIR = Path(__file__).resolve().parent


@dataclass
class BakedGlyph:
    codepoint: int
    advance: float
    bounds: tuple[float, float, float, float]
    pixels: np.ndarray | None
    x: int = 0
    y: int = 0


def signed_distance(coverage: np.ndarray) -> np.ndarray:
    """Extend alpha - 0.5 contour offsets with EDTs to preserve subpixel edges."""
    if not np.any(coverage > 0.0) or not np.any(coverage == 0.0):
        raise ValueError('A glyph needs ink and an empty exterior padding region')
    opaque = coverage == 1.0
    empty = coverage == 0.0
    distance_in, nearest_nonopaque = distance_transform_edt(
        opaque, return_indices=True
    )
    distance_out, nearest_nonempty = distance_transform_edt(
        empty, return_indices=True
    )
    contour = coverage - 0.5
    result = contour.copy()
    result[opaque] = (
        distance_in + contour[tuple(nearest_nonopaque)]
    )[opaque]
    result[empty] = (
        -distance_out + contour[tuple(nearest_nonempty)]
    )[empty]
    return result


def encode_distance(distance: np.ndarray) -> np.ndarray:
    normalized = np.clip(0.5 + distance / (2.0 * SDF_RANGE), 0.0, 1.0)
    return np.floor(normalized * 255.0 + 0.5).astype(np.uint8)


def rasterize(font: ImageFont.FreeTypeFont, codepoint: int, ascent: int) -> BakedGlyph:
    character = chr(codepoint)
    advance = float(font.getlength(character))
    if codepoint in SPACES:
        return BakedGlyph(codepoint, advance, (0.0, 0.0, 0.0, 0.0), None)

    # 'ls' measures from the left baseline. Translate y by ascent to line TOP.
    x0, y0, x1, y1 = font.getbbox(character, anchor='ls')
    width = x1 - x0 + 2 * PADDING
    height = y1 - y0 + 2 * PADDING
    image = Image.new('L', (width, height), 0)
    ImageDraw.Draw(image).text(
        (PADDING - x0, PADDING - y0), character,
        font=font, fill=255, anchor='ls',
    )
    coverage = np.asarray(image, dtype=np.float64) / 255.0
    pixels = encode_distance(signed_distance(coverage))
    bounds = (
        float(x0 - PADDING), float(y0 + ascent - PADDING),
        float(x1 + PADDING), float(y1 + ascent + PADDING),
    )
    return BakedGlyph(codepoint, advance, bounds, pixels)


def pack(glyphs: list[BakedGlyph]) -> np.ndarray:
    """Stable shelf packing in codepoint order, with a power-of-two height."""
    x = y = row_height = 0
    for glyph in glyphs:
        if glyph.pixels is None:
            continue
        height, width = glyph.pixels.shape
        if width > ATLAS_WIDTH:
            raise ValueError(f'U+{glyph.codepoint:04X} is wider than the atlas')
        if x + width > ATLAS_WIDTH:
            y += row_height
            x = row_height = 0
        glyph.x, glyph.y = x, y
        x += width
        row_height = max(row_height, height)
    used_height = y + row_height
    atlas_height = 1 << (used_height - 1).bit_length()
    atlas = np.zeros((atlas_height, ATLAS_WIDTH), dtype=np.uint8)
    for glyph in glyphs:
        if glyph.pixels is not None:
            height, width = glyph.pixels.shape
            atlas[glyph.y:glyph.y + height, glyph.x:glyph.x + width] = glyph.pixels
    return atlas


def rust_float(value: float) -> str:
    """Emit decimal Rust f32 literals, including 0.0 and integral values."""
    literal = np.format_float_positional(np.float32(value), unique=True, trim='-')
    return literal if '.' in literal else literal + '.0'


def rust_array(values: tuple[float, ...]) -> str:
    return '[' + ', '.join(rust_float(value) for value in values) + ']'


def metrics_source(
    glyphs: list[BakedGlyph], atlas_height: int, ascent: int, descent: int,
    font_sha256: str,
) -> str:
    lines = [
        '// Generated by bake.py; do not edit. See LICENSE-DejaVu.txt.',
        f'// Input TTF SHA-256: {font_sha256}',
        f'// Pillow {PIL.__version__}; FreeType {features.version("freetype2")}; '
        f'numpy {np.__version__}; scipy {scipy.__version__}; layout BASIC.',
        '// Use include!("../assets/font_metrics.rs") from src/text.rs; '
        'the including module supplies Glyph.',
        '// Order: U+0020..U+007E, then U+00A0..U+00FF. '
        'Index = cp - 32 or 95 + cp - 160.',
        '// Unsupported codepoints fall back to U+003F (\'?\'), index 31, at runtime.',
        f'// Bounds: [x0, y0, x1, y1], including {PADDING}px padding; '
        f'line TOP origin, baseline y={ascent}.',
        '// UV: [u0, v0, u1, v1], rectangle edges, top-left origin; '
        'raw R8 rows run top to bottom.',
        '// Space and NBSP only advance the pen: zero bounds and UV, no atlas tile.',
        '// Encode: floor(255 * clamp(0.5 + d / 64.0, 0.0, 1.0) + 0.5); '
        'd is positive inside.',
        '// Decode: d = (sample_unorm - 0.5) * 64.0; '
        'the zero contour is 0.5 before R8 quantization.',
        f'pub(super) const FONT_SIZE: f32 = {rust_float(FONT_SIZE)};',
        f'pub(super) const LINE_HEIGHT: f32 = {rust_float(ascent + descent)};',
        f'pub(super) const ATLAS_WIDTH: u32 = {ATLAS_WIDTH};',
        f'pub(super) const ATLAS_HEIGHT: u32 = {atlas_height};',
        f'pub(super) const SDF_RANGE: f32 = {rust_float(SDF_RANGE)};',
        '// Exact f32 decimal expansions of atlas-edge fractions trip excessive_precision.',
        '#[allow(clippy::excessive_precision)]',
        f'pub(super) const GLYPHS: [Glyph; {len(glyphs)}] = [',
    ]
    for glyph in glyphs:
        uv = (0.0, 0.0, 0.0, 0.0)
        if glyph.pixels is not None:
            height, width = glyph.pixels.shape
            uv = (
                glyph.x / ATLAS_WIDTH, glyph.y / atlas_height,
                (glyph.x + width) / ATLAS_WIDTH,
                (glyph.y + height) / atlas_height,
            )
        lines.append(
            f'    Glyph {{ advance: {rust_float(glyph.advance)}, '
            f'bounds: {rust_array(glyph.bounds)}, uv: {rust_array(uv)} }}, '
            f'// U+{glyph.codepoint:04X}'
        )
    lines.append('];')
    return '\n'.join(lines) + '\n'


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('ttf', nargs='?', type=Path, default=DEFAULT_TTF,
                        help=f'input TrueType font (default: {DEFAULT_TTF})')
    args = parser.parse_args()
    font = ImageFont.truetype(str(args.ttf), FONT_SIZE, layout_engine=ImageFont.Layout.BASIC)
    ascent, descent = font.getmetrics()
    glyphs = [rasterize(font, codepoint, ascent) for codepoint in CODEPOINTS]
    atlas = pack(glyphs)
    atlas_height = atlas.shape[0]
    raw = atlas.tobytes(order='C')

    assert len(glyphs) == 191
    assert tuple(glyph.codepoint for glyph in glyphs) == CODEPOINTS
    assert len(raw) == ATLAS_WIDTH * atlas_height
    assert atlas_height > 0 and atlas_height & (atlas_height - 1) == 0
    for glyph in glyphs:
        if glyph.pixels is None:
            assert glyph.codepoint in SPACES and glyph.bounds == (0.0,) * 4
            continue
        height, width = glyph.pixels.shape
        x0, y0, x1, y1 = glyph.bounds
        assert (x1 - x0, y1 - y0) == (width, height)
        assert glyph.x + width <= ATLAS_WIDTH and glyph.y + height <= atlas_height
        # A saturated exterior perimeter prevents bilinear bleed across tiles.
        assert not np.any(glyph.pixels[[0, -1], :])
        assert not np.any(glyph.pixels[:, [0, -1]])

    font_sha256 = hashlib.sha256(args.ttf.read_bytes()).hexdigest()
    source = metrics_source(glyphs, atlas_height, ascent, descent, font_sha256)
    (OUTPUT_DIR / 'font.r8').write_bytes(raw)
    (OUTPUT_DIR / 'font_metrics.rs').write_text(source, encoding='utf-8', newline='\n')
    print(f'{ATLAS_WIDTH}x{atlas_height} R8: {len(raw)} bytes; {len(glyphs)} glyphs; '
          f'baseline {ascent}, descent {descent}, line height {ascent + descent}')
    for name in ('font.r8', 'font_metrics.rs'):
        path = OUTPUT_DIR / name
        print(f'{path}: {path.stat().st_size} bytes; '
              f'SHA-256 {hashlib.sha256(path.read_bytes()).hexdigest()}')


if __name__ == '__main__':
    main()
